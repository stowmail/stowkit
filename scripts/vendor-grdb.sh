#!/usr/bin/env bash
# Vendors GRDB.swift into Vendor/GRDB, built against SQLCipher (D-011).
#
# GRDB's documented route to SQLCipher through SwiftPM is to edit its
# Package.swift (search "GRDB+SQLCipher" in the upstream manifest). Rather than
# keep a fork on GitHub, this script downloads a tagged release, keeps only the
# library sources and licence, and writes the edited manifest below.
#
# SQLCipher itself comes from the local package Vendor/SQLCipher, fetched by
# scripts/fetch-sqlcipher.sh (bump its version there).
#
# Usage: scripts/vendor-grdb.sh [grdb-version]
# To update: change the defaults, rerun, then run scripts/check.sh.

set -euo pipefail

GRDB_VERSION="${1:-7.11.1}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/Vendor/GRDB"
WORK="$(mktemp -d)"
trap '/bin/rm -rf "$WORK"' EXIT

echo "Downloading GRDB.swift v$GRDB_VERSION"
curl -fsSL "https://github.com/groue/GRDB.swift/archive/refs/tags/v$GRDB_VERSION.tar.gz" -o "$WORK/grdb.tgz"
tar -xzf "$WORK/grdb.tgz" -C "$WORK"
SRC="$WORK/GRDB.swift-$GRDB_VERSION"

# Sanity check: the upstream manifest still documents the SQLCipher edits this
# script reproduces. If this fails, read the new upstream Package.swift first.
grep -q 'GRDB+SQLCipher' "$SRC/Package.swift" || { echo "Upstream manifest changed; review before vendoring" >&2; exit 1; }
grep -q 'import GRDBSQLCipher' "$SRC/GRDB/Core/Database.swift" || { echo "GRDBSQLCipher import missing upstream" >&2; exit 1; }

if [ -d "$DEST" ]; then mv "$DEST" "$WORK/previous"; fi
mkdir -p "$DEST/Sources"
cp -R "$SRC/GRDB" "$DEST/GRDB"
cp -R "$SRC/Sources/GRDBSQLCipher" "$DEST/Sources/GRDBSQLCipher"
cp "$SRC/LICENSE" "$DEST/LICENSE"

cat > "$DEST/Package.swift" <<EOF
// swift-tools-version:6.1
// Generated by scripts/vendor-grdb.sh from GRDB.swift v$GRDB_VERSION (D-011).
// Do not edit by hand: rerun the script instead.
//
// This is GRDB's own manifest with its documented "GRDB+SQLCipher" edits
// applied: the system SQLite target is removed and SQLCipher takes its place.

import PackageDescription

let package = Package(
    name: "GRDB",
    platforms: [.macOS(.v10_15)],
    products: [
        .library(name: "GRDB", targets: ["GRDB"]),
    ],
    dependencies: [
        .package(path: "../SQLCipher"),
    ],
    targets: [
        .target(
            name: "GRDBSQLCipher",
            dependencies: [.product(name: "SQLCipher", package: "SQLCipher")]
        ),
        .target(
            name: "GRDB",
            dependencies: [
                .product(name: "SQLCipher", package: "SQLCipher"),
                .target(name: "GRDBSQLCipher"),
            ],
            path: "GRDB",
            resources: [.copy("PrivacyInfo.xcprivacy")],
            cSettings: [
                .define("SQLITE_HAS_CODEC"),
            ],
            swiftSettings: [
                .define("SQLITE_ENABLE_FTS5"),
                .define("SQLITE_ENABLE_SNAPSHOT"),
                .define("SQLITE_HAS_CODEC"),
                .define("SQLCipher"),
                .enableUpcomingFeature("MemberImportVisibility"),
            ]
        ),
    ],
    swiftLanguageModes: [.v6]
)
EOF

cat > "$DEST/VENDORED.md" <<EOF
# Vendored GRDB.swift

- Upstream: https://github.com/groue/GRDB.swift, tag v$GRDB_VERSION (MIT, see LICENSE)
- SQLCipher: local package \`../SQLCipher\` (Zetetic xcframework, see scripts/fetch-sqlcipher.sh)
- Contents: \`GRDB/\` and \`Sources/GRDBSQLCipher/\` unchanged from upstream; \`Package.swift\` generated.
- Why vendored rather than forked: see D-011 in the Stow decision log.
- Regenerate with \`scripts/vendor-grdb.sh\`. Never edit files here by hand.
EOF

echo "Vendored GRDB v$GRDB_VERSION into Vendor/GRDB"
